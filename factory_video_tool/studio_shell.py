"""Native page assembly. Production services remain on the window controller."""
from pathlib import Path
from PySide6.QtCore import Qt,QSize
from PySide6.QtGui import QPixmap
from PySide6.QtWidgets import (QWidget,QVBoxLayout,QHBoxLayout,QFormLayout,QFrame,QStackedWidget,
    QLineEdit,QComboBox,QPlainTextEdit,QSpinBox,QSlider,QListWidget,QProgressBar,QSplitter,QStyle,QCheckBox)
from PySide6.QtMultimedia import QMediaPlayer,QAudioOutput
from PySide6.QtMultimediaWidgets import QVideoWidget
from .studio_widgets import label,button,page,scroll,divider,STYLE,PortraitPreview
from .release_panels import ReleasePanel


def build_shell(w):
    w.setStyleSheet(STYLE)
    root=QHBoxLayout(w);root.setContentsMargins(0,0,0,0);root.setSpacing(0)
    sidebar=QFrame();sidebar.setObjectName('sidebar');sidebar.setFixedWidth(200)
    side=QVBoxLayout(sidebar);side.setContentsMargins(16,30,16,20);side.setSpacing(10)
