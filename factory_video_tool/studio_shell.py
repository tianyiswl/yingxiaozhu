    w.resolution=QComboBox();w.resolution.addItems(['1080 × 1920','720 × 1280']);af.addRow('竖屏尺寸',w.resolution)
    w.bgm=QLineEdit();w.bgm.setPlaceholderText('不添加背景音乐');w.bgm_button=button('选择音乐',w.pick_bgm)
    row=QHBoxLayout();row.addWidget(w.bgm,1);row.addWidget(w.bgm_button);row.addWidget(button('移除音乐',w.bgm.clear));af.addRow('背景音乐',row)
