    w.title_edit.textEdited.connect(w.inline_content_changed);w.voice_edit.textChanged.connect(w.inline_content_changed)
    cl.setContentsMargins(12,12,12,12);cl.setSpacing(12);w.wizard.addWidget(scroll(content))

