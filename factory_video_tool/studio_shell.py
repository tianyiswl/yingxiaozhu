    home.addLayout(hero,3);home.addWidget(divider())
    steps=QHBoxLayout();steps.setSpacing(24)
    for n,title,sub in [('1','选择素材与文案','导入本地拍摄的视频和文档'),('2','试听配音并生成','选择系统声音，开始制作'),('3','预览视频，保存到电脑','查看效果，导出本地视频文件')]:
        l=QVBoxLayout();l.addWidget(label(n+'   '+title,'section'));l.addWidget(label(sub,'muted'));steps.addLayout(l,1)
