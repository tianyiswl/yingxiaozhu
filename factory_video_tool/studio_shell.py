    save.addWidget(w.save_destination);w.save_directory=QLineEdit();w.save_directory.setPlaceholderText('填写已有文件夹的完整路径');w.save_directory.hide();save.addWidget(w.save_directory)
    w.save_destination.currentIndexChanged.connect(lambda i:w.save_directory.setVisible(i==3))
    row=QHBoxLayout();w.confirm_save=button('确认保存',w.save_export,True);row.addWidget(w.confirm_save);row.addWidget(button('返回预览',w.hide_save_panel));save.addLayout(row)
    w.save_panel.hide();rl.addWidget(w.save_panel)
