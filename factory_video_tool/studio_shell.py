    w.stop_audition=button('停止试听',lambda:w.audition_player.stop());row.addWidget(w.stop_audition);al.addLayout(row)
    al.addWidget(label('系统中文音色由电脑提供；字幕按口播长度估算，生成后请预览核对。','muted'))
    w.more_audio=button('调整画面与背景音乐');w.more_audio.setCheckable(True);al.addWidget(w.more_audio)
