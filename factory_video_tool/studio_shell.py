    row=QHBoxLayout();w.import_button=button('导入文档',w.import_excel,True,QStyle.SP_FileIcon);row.addWidget(w.import_button)
    w.new_content=button('直接写一条',w.create_content);row.addWidget(w.new_content);row.addStretch();cl.addLayout(row)
    cl.addWidget(label('支持 TXT、DOCX、Excel。可选择一条或勾选多条制作。','muted'))
