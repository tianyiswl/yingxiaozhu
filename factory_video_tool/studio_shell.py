    for t,d in [('1  选择素材与文案','选择对应产品的视频文件夹，再导入本地文档。TXT / DOCX 第一行是标题，其余文字作为口播；Excel 使用 title、voice_text 两列。'),('2  试听并生成','选择系统声音，试听前100字。背景音乐可以留空。默认竖屏1080p，字幕会自动添加。'),('3  预览与保存','检查口播、画面和字幕，点击“保存到电脑”。只有主动准备发布时才需要抖音账号。')]:hl.addWidget(label(t,'section'));hl.addWidget(label(d,'muted'))
    w.demo_button=button('载入合成示例（会替换当前编辑内容）',w.load_demo_confirmed);hl.addWidget(w.demo_button)
    w.log=QPlainTextEdit();w.log.setReadOnly(True);w.log.setMaximumHeight(180);hl.addWidget(label('诊断详情','section'));hl.addWidget(w.log);hl.addStretch();w.help_scroll=scroll(w.help_page);w.pages.addWidget(w.help_scroll)
    w.progress=QProgressBar();w.progress.setTextVisible(False);w.progress.setMaximumHeight(6);w.progress.hide();column.addWidget(w.progress)
    footer=QHBoxLayout();footer.setContentsMargins(24,6,24,8);w.status=label('正在准备本地制作环境…','muted');footer.addWidget(w.status,1)
    w.cancel_button=button('停止当前操作',w.cancel_job);w.cancel_button.hide();footer.addWidget(w.cancel_button);column.addLayout(footer)
