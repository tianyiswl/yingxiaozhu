    advanced.hide();w.more_audio.toggled.connect(advanced.setVisible);al.addWidget(advanced)
    w.generation_summary=label();al.addWidget(w.generation_summary);al.addStretch()
    w.start_button=button('生成这条视频',w.start_generation,True,QStyle.SP_MediaPlay);w.batch_button=button('生成勾选文案',w.start_batch)
    al.setContentsMargins(12,12,12,12);al.setSpacing(12);w.wizard.addWidget(scroll(audio));w.step_error=label('','error');creation.addWidget(w.step_error)
    row=QHBoxLayout();w.previous=button('上一步',w.previous_step);row.addWidget(w.previous);row.addStretch();w.next_step=button('下一步：准备文案',w.advance_step,True);row.addWidget(w.next_step);row.addWidget(w.batch_button);row.addWidget(w.start_button);creation.addLayout(row)
    w.pages.addWidget(w.creation_page)

