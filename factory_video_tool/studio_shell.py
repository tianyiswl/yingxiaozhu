    copy.addWidget(label('把车间素材和文案准备好，剩下的跟着步骤走。','muted'))
    copy.addSpacing(16)
    w.home_start=button('制作第一条视频',w.begin_creation,True, QStyle.SP_MediaPlay);w.home_start.setMinimumHeight(64);w.home_start.setStyleSheet("font-size:20px;font-weight:600;");w.home_start.setMaximumWidth(400);copy.addWidget(w.home_start)
