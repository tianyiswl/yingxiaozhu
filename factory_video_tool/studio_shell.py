    w.video_list=QListWidget();w.video_list.setIconSize(QSize(48,72));w.video_list.currentItemChanged.connect(w.video_selected);ll.addWidget(w.video_list,1)
    w.video_error=label('','error');ll.addWidget(w.video_error)
    ll.addWidget(w.release_panel.retry_button);splitter.addWidget(left)
    right=QWidget();rl=QVBoxLayout(right);rl.setContentsMargins(12,0,0,0)
