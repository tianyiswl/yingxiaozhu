    w.seek=QSlider(Qt.Horizontal);w.seek.setRange(0,0);rl.addWidget(w.seek)
    w.time_label=label('00:00 / 00:00','muted');rl.addWidget(w.time_label)
    w.player.durationChanged.connect(lambda d:w.seek.setRange(0,d));w.player.positionChanged.connect(w.seek.setValue);w.player.positionChanged.connect(w.update_playback_time);w.seek.sliderMoved.connect(w.player.setPosition)
    row=QHBoxLayout();w.play=button('播放 / 暂停',w.toggle_play,icon=QStyle.SP_MediaPlay);w.export=button('保存到电脑',w.export_result,True);row.addWidget(w.play);row.addWidget(w.export);rl.addLayout(row)
    row=QHBoxLayout();w.folder=button('打开成片目录',w.open_folder);w.to_publish=button('准备发布这条视频',w.open_publish_page);row.addWidget(w.folder);row.addWidget(w.to_publish);rl.addLayout(row)
