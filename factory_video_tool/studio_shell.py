    w.video_status=label('生成的视频会出现在左侧。','muted');rl.addWidget(w.video_status)
    w.preview_stack=QStackedWidget();w.video_empty=label('还没有可预览的视频\n\n先制作一条，或从左侧选择已完成的视频。','muted');w.video_empty.setAlignment(Qt.AlignCenter);w.preview_stack.addWidget(w.video_empty)
